import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean }
>(({ className, hoverEffect = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-border bg-card p-6 text-card-foreground shadow-card transition-all duration-200",
      hoverEffect && "hover:-translate-y-1 hover:shadow-soft hover:border-slate-300",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

